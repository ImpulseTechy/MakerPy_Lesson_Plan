// BigBoT Teacher Hub — static site build. Usage: node build.js
// Loads content, validates it (build fails on any error), renders every page to dist/.
import { mkdir, rm, writeFile, cp } from "node:fs/promises";
import path from "node:path";
import { loadContent, ROOT } from "./lib/load.js";
import { validate } from "./lib/validate.js";
import { sessionPath } from "./lib/html.js";
import { lessonPage } from "./lib/pages/lesson.js";
import {
  homePage, coursePage, pinMapPage, componentsPage, codePage,
  troubleshootingPage, teachingPage, updatesPage, notFoundPage
} from "./lib/pages/site.js";

const DIST = path.join(ROOT, "dist");

async function main() {
  const started = Date.now();
  const content = await loadContent();
  validate(content);

  const pages = [
    homePage(content),
    coursePage(content),
    ...content.sessions.map((s) => lessonPage(s, content)),
    pinMapPage(content),
    componentsPage(content),
    codePage(content),
    troubleshootingPage(content),
    teachingPage(content),
    updatesPage(content),
    notFoundPage(content)
  ];

  await rm(DIST, { recursive: true, force: true });
  for (const p of pages) {
    const file = path.join(DIST, p.path);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, p.html);
  }
  await cp(path.join(ROOT, "src/assets"), path.join(DIST, "assets"), { recursive: true });
  await cp(path.join(ROOT, "public"), DIST, { recursive: true });
  await writeFile(path.join(DIST, "assets/search-index.js"), searchIndex(content));

  const full = content.sessions.filter((s) => s.status === "full").length;
  console.log(`Built ${pages.length} pages (${full} full ${full === 1 ? "lesson" : "lessons"}, ${content.sessions.length - full} outlines) in ${Date.now() - started} ms → dist/`);
}

function searchIndex({ sessions, components, pins }) {
  const items = [];
  for (const s of sessions) {
    items.push({
      t: `Session ${s.number}: ${s.title}`,
      d: s.output,
      g: `Phase ${s.phase} · ${s.status === "full" ? "Full lesson" : "Outline"}`,
      u: sessionPath(s.number),
      k: [s.title, s.electronics, s.coding, s.componentsText, s.output, s.moduleTopic].join(" ").toLowerCase()
    });
  }
  for (const c of components.items) {
    items.push({ t: c.name, d: c.pins !== "—" ? c.pins : c.detail, g: "Component", u: `makerpy/components/index.html#${c.id}`, k: `${c.name} ${c.detail} ${c.pins}`.toLowerCase() });
  }
  for (const p of pins.pins) {
    items.push({ t: `GPIO ${p.gpio}`, d: p.use, g: "Pin Map", u: `makerpy/pin-map/index.html#gpio-${p.gpio}`, k: `gpio ${p.gpio} gp${p.gpio} ${p.use} ${p.where}`.toLowerCase() });
  }
  const pagesList = [
    ["Pin Map", "makerpy/pin-map/index.html"], ["Components", "makerpy/components/index.html"],
    ["Code library", "makerpy/code/index.html"], ["Troubleshooting", "makerpy/troubleshooting/index.html"],
    ["Teaching Online Guide", "teaching-online/index.html"], ["Updates", "updates/index.html"], ["MakerPy course", "makerpy/index.html"]
  ];
  for (const [t, u] of pagesList) items.push({ t, d: "", g: "Page", u, k: t.toLowerCase() });
  return `// Generated by build.js — do not edit.\nwindow.BIGBOT_SEARCH = ${JSON.stringify(items)};\n`;
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
